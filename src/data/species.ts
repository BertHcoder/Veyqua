import type { InhabitantKind, L10n, Range, Water } from '../lib/types';

/**
 * Parameters a species narrows the tank targets on. Marine species only set temperature:
 * published pH and salinity ranges for marine fish are generic, and the reef or fish-only
 * profile is a better guide for those.
 */
export type SpeciesParam = 'temperature' | 'ph' | 'gh';

export interface Species {
  id: string;
  scientificName?: string;
  name: L10n;
  kind: Exclude<InhabitantKind, 'plant' | 'other'>;
  water: Water;
  /** Comfort ranges in canonical units (°C, pH, dGH). */
  ranges: Partial<Record<SpeciesParam, Range>>;
  /** Smallest group that keeps a shoaling or social species comfortable. */
  minGroup?: number;
  /** Commonly recommended minimum aquarium volume in litres. */
  minVolumeL?: number;
  /** Marine only: safe with corals and invertebrates. */
  reefSafe?: boolean | 'caution';
  care: L10n;
}

